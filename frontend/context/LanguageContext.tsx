const languageStorageKey = 'language'
const languageChangeEvent = 'wsmis-language-change'

const getStoredLanguage = (): Language => {
  const saved = window.localStorage.getItem(languageStorageKey)
  return saved === 'fa' ? 'fa' : 'en'
}

const getServerLanguage = (): Language => 'en'

const subscribeToLanguage = (notify: () => void) => {
  const handleStorage = (event: StorageEvent) => {
    if (event.key === null || event.key === languageStorageKey) notify()
  }
  const handleLanguageChange = () => notify()

  window.addEventListener('storage', handleStorage)
  window.addEventListener(languageChangeEvent, handleLanguageChange)

  return () => {
    window.removeEventListener('storage', handleStorage)
    window.removeEventListener(languageChangeEvent, handleLanguageChange)
  }
}

