const getTranslatedText = (value: string, language: Language) => {
  if (language === 'en') return value
  const translation = getPersianPhrase(value)
  return translation ? preserveSpacing(value, translation) : value
}

const shouldSkipElement = (element: Element | null) => {
  if (!element) return true
  const tagName = element.tagName.toLowerCase()
  return ['script', 'style', 'textarea', 'input'].includes(tagName)
    || Boolean(element.closest('[data-no-translate], [contenteditable="true"]'))
}

const translateStaticText = (root: ParentNode, language: Language) => {
  if (typeof document === 'undefined') return

  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      const parent = node.parentElement
      if (shouldSkipElement(parent)) return NodeFilter.FILTER_REJECT
      if (!normalizeText(node.textContent ?? '')) return NodeFilter.FILTER_REJECT
      return NodeFilter.FILTER_ACCEPT
    },
  })

  let current = walker.nextNode() as Text | null
  while (current) {
    if (language === 'en') {
      const original = originalTextNodes.get(current)
      if (original !== undefined && current.data !== original) current.data = original
    } else {
      const original = originalTextNodes.get(current) ?? current.data
      const translated = getTranslatedText(original, language)
      if (translated !== original) {
        if (!originalTextNodes.has(current)) originalTextNodes.set(current, original)
        if (current.data !== translated) current.data = translated
      }
    }
    current = walker.nextNode() as Text | null
  }

  root.querySelectorAll?.('*').forEach((element) => {
    if (!(element instanceof HTMLElement) || shouldSkipElement(element)) return

    attributeNames.forEach((attribute) => {
      const value = element.getAttribute(attribute)
      const dataKey = dataKeyForAttribute(attribute)
      const original = element.dataset[dataKey]

      if (language === 'en') {
        if (original !== undefined) {
          element.setAttribute(attribute, original)
          delete element.dataset[dataKey]
        }
        return
      }

      if (!value) return
      const nextOriginal = original ?? value
      const translated = getTranslatedText(nextOriginal, language)
      if (translated !== nextOriginal) {
        element.dataset[dataKey] = nextOriginal
        element.setAttribute(attribute, translated)
      }
    })
  })
}

